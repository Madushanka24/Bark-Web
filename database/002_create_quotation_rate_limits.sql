BEGIN;

-- ============================================
-- 1. RATE-LIMIT COUNTER TABLE
-- ============================================

CREATE TABLE IF NOT EXISTS
    public.quotation_rate_limits
(
    id BIGINT GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,

    -- Examples: ip, email
    identity_type VARCHAR(20) NOT NULL,

    -- Keyed SHA-256 HMAC generated by the API.
    -- Stored as 64 hexadecimal characters.
    identity_hash VARCHAR(64) NOT NULL,

    -- Number of seconds in this fixed window.
    window_seconds INTEGER NOT NULL,

    -- UTC-based start of the time window.
    window_start TIMESTAMPTZ NOT NULL,

    -- Number of accepted attempts in window.
    attempt_count INTEGER NOT NULL DEFAULT 1,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT qrl_identity_type_check
        CHECK (
            identity_type IN ('ip', 'email')
        ),

    CONSTRAINT qrl_identity_hash_check
        CHECK (
            identity_hash ~ '^[0-9a-f]{64}$'
        ),

    CONSTRAINT qrl_window_seconds_check
        CHECK (
            window_seconds BETWEEN 60 AND 86400
        ),

    CONSTRAINT qrl_attempt_count_check
        CHECK (attempt_count >= 1),

    CONSTRAINT qrl_unique_window
        UNIQUE (
            identity_type,
            identity_hash,
            window_seconds,
            window_start
        )
);

-- ============================================
-- 2. CLEANUP INDEX
-- ============================================

CREATE INDEX IF NOT EXISTS
    idx_qrl_window_start
ON public.quotation_rate_limits
    (window_start);

-- ============================================
-- 3. ATOMIC RATE-LIMIT FUNCTION
--
-- Parameters:
-- p_identity_type: 'ip' or 'email'
-- p_identity_hash: 64-character HMAC hex
-- p_max_attempts: allowed attempts
-- p_window_seconds: window duration
--
-- Returns:
-- allowed: whether request is permitted
-- attempts: accepted attempts in window
-- retry_after_seconds: seconds until reset
--
-- Example policy:
-- maximum 5 attempts in 3600 seconds.
-- ============================================

CREATE OR REPLACE FUNCTION
public.check_quotation_rate_limit(
    p_identity_type TEXT,
    p_identity_hash TEXT,
    p_max_attempts INTEGER DEFAULT 5,
    p_window_seconds INTEGER DEFAULT 3600
)
RETURNS TABLE (
    allowed BOOLEAN,
    attempts INTEGER,
    retry_after_seconds INTEGER
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
    v_now TIMESTAMPTZ;
    v_window_start TIMESTAMPTZ;
    v_window_end TIMESTAMPTZ;
    v_attempts INTEGER;
    v_retry_after INTEGER;
BEGIN

    -- Validate inputs before writing data.

    IF p_identity_type IS NULL
       OR p_identity_type NOT IN ('ip', 'email')
    THEN
        RAISE EXCEPTION
            'Invalid identity type';
    END IF;

    IF p_identity_hash IS NULL
       OR p_identity_hash !~ '^[0-9a-f]{64}$'
    THEN
        RAISE EXCEPTION
            'Invalid identity hash';
    END IF;

    IF p_max_attempts IS NULL
       OR p_max_attempts NOT BETWEEN 1 AND 100
    THEN
        RAISE EXCEPTION
            'Invalid attempt limit';
    END IF;

    IF p_window_seconds IS NULL
       OR p_window_seconds NOT BETWEEN 60 AND 86400
    THEN
        RAISE EXCEPTION
            'Invalid window duration';
    END IF;

    -- Use database time so all website
    -- instances share the same clock.

    v_now := clock_timestamp();

    -- Fixed window aligned to Unix epoch.

    v_window_start := to_timestamp(
        floor(
            extract(epoch FROM v_now)
            / p_window_seconds
        ) * p_window_seconds
    );

    v_window_end :=
        v_window_start
        + make_interval(secs => p_window_seconds);

    v_retry_after := greatest(
        1,
        ceil(
            extract(epoch FROM (v_window_end - v_now))
        )::INTEGER
    );

    -- Atomically insert or increment.
    -- The conflict update refuses to
    -- increment beyond p_max_attempts.

    INSERT INTO public.quotation_rate_limits AS qrl (
        identity_type,
        identity_hash,
        window_seconds,
        window_start,
        attempt_count,
        created_at,
        updated_at
    )
    VALUES (
        p_identity_type,
        p_identity_hash,
        p_window_seconds,
        v_window_start,
        1,
        v_now,
        v_now
    )
    ON CONFLICT (
        identity_type,
        identity_hash,
        window_seconds,
        window_start
    )
    DO UPDATE SET
        attempt_count = qrl.attempt_count + 1,
        updated_at = v_now
    WHERE qrl.attempt_count < p_max_attempts
    RETURNING attempt_count
    INTO v_attempts;

    IF v_attempts IS NOT NULL THEN
        RETURN QUERY
        SELECT
            TRUE,
            v_attempts,
            0;
        RETURN;
    END IF;

    -- The existing counter is already
    -- at its permitted maximum.

    SELECT qrl.attempt_count
    INTO v_attempts
    FROM public.quotation_rate_limits AS qrl
    WHERE qrl.identity_type = p_identity_type
      AND qrl.identity_hash = p_identity_hash
      AND qrl.window_seconds = p_window_seconds
      AND qrl.window_start = v_window_start;

    RETURN QUERY
    SELECT
        FALSE,
        coalesce(v_attempts, p_max_attempts),
        v_retry_after;

END;
$function$;

-- ============================================
-- 4. RESTRICT DIRECT TABLE ACCESS
--
-- The website runtime should call the
-- function, not modify counters directly.
-- ============================================

REVOKE ALL ON TABLE
    public.quotation_rate_limits
FROM PUBLIC;

REVOKE ALL ON TABLE
    public.quotation_rate_limits
FROM bark_web_dev;

REVOKE ALL ON SEQUENCE
    public.quotation_rate_limits_id_seq
FROM PUBLIC;

REVOKE ALL ON SEQUENCE
    public.quotation_rate_limits_id_seq
FROM bark_web_dev;

REVOKE ALL ON FUNCTION
    public.check_quotation_rate_limit(
        TEXT, TEXT, INTEGER, INTEGER
    )
FROM PUBLIC;

GRANT USAGE ON SCHEMA public
TO bark_web_dev;

GRANT EXECUTE ON FUNCTION
    public.check_quotation_rate_limit(
        TEXT, TEXT, INTEGER, INTEGER
    )
TO bark_web_dev;

COMMIT;

